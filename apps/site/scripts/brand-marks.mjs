// Regenerates src/lib/brand-marks.ts from Simple Icons.
//
//   node scripts/brand-marks.mjs
//
// Run it when an integration is added whose vendor has a mark, or to move to a newer icon set.
// The output is committed, so the site build never reaches the network and the repo carries no
// dependency for eleven paths. Vendors with no Simple Icons entry are absent on purpose — they
// fall back to the monogram tile, which is a deliberate design, not a gap to fill by redrawing
// somebody's logo from memory.

import { writeFile } from 'node:fs/promises';

const VERSION = '15';

// Integration slug (src/data/integrations/*.json) → Simple Icons slug. They differ wherever the
// vendor's product name and its brand mark are not the same thing: Google Workspace is drawn
// with the Google G, OIDC is the OpenID mark, and "MCP" is Anthropic's protocol logo.
//
// Adyen is deliberately absent even though `simple-icons/adyen` exists: it is a *wordmark*, and
// five letterforms in a 44px tile render as a smudge. A mark has to survive the size the tile
// actually is, so the test for adding one here is looking at it at 2.75rem, not that it exists.
const MARKS = {
  anthropic: 'anthropic',
  cloudflare: 'cloudflare',
  'google-ads': 'googleads',
  'google-analytics': 'googleanalytics',
  'google-workspace': 'google',
  'google-tag-manager': 'googletagmanager',
  'search-console': 'googlesearchconsole',
  mcp: 'modelcontextprotocol',
  oidc: 'openid',
  openai: 'openai',
  stripe: 'stripe',
  'uptime-kuma': 'uptimekuma',
  wordpress: 'wordpress',
};

const entries = [];

for (const [slug, icon] of Object.entries(MARKS)) {
  const url = `https://cdn.jsdelivr.net/npm/simple-icons@${VERSION}/icons/${icon}.svg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${icon}: HTTP ${res.status} — check the slug at simpleicons.org`);

  const svg = await res.text();
  const path = svg.match(/ d="([^"]+)"/)?.[1];
  const title = svg.match(/<title>([^<]+)<\/title>/)?.[1] ?? icon;
  if (!path) throw new Error(`${icon}: no path found; the icon format changed`);

  entries.push({ slug, icon, title, path });
  console.log(`${slug.padEnd(20)} ${icon} (${path.length} chars)`);
}

const body = entries
  .map(
    (e) =>
      `  // ${e.title} — simple-icons/${e.icon}\n  '${e.slug}': ${JSON.stringify(e.path)},`,
  )
  .join('\n');

await writeFile(
  new URL('../src/lib/brand-marks.ts', import.meta.url),
  `// GENERATED by scripts/brand-marks.mjs — do not edit by hand.
//
// Vendor brand marks, keyed by integration slug. Each value is the \`d\` of a single path on a
// 24×24 viewBox, drawn in \`currentColor\` so one path serves both themes and any tint.
//
// Source: Simple Icons v${VERSION} (https://simpleicons.org), whose icon files are CC0-1.0. The
// marks themselves remain the trademarks of their owners; naming a service you integrate with is
// what they are used for here, and nothing is recoloured beyond the vendor's own brand colour or
// redrawn. A vendor absent from this map keeps the monogram tile.
//
// Regenerate: \`node scripts/brand-marks.mjs\` from apps/site.

export const brandMarks: Record<string, string> = {
${body}
};
`,
  'utf8',
);

console.log(`\nWrote ${entries.length} marks to src/lib/brand-marks.ts`);
